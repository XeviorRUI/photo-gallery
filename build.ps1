#requires -Version 5.1
[CmdletBinding()]
param(
  [string]$Root = '',
  [string]$Output = 'dist',
  [ValidateRange(320, 2400)][int]$ThumbnailMaxSide = 1080,
  [ValidateRange(960, 6000)][int]$DetailMaxSide = 2560,
  [ValidateRange(45, 95)][int]$ThumbnailQuality = 78,
  [ValidateRange(60, 100)][int]$DetailQuality = 88,
  [ValidatePattern('^#[0-9A-Fa-f]{6}$')][string]$MatteColor = '#FFFFFF',
  [string]$SiteUrl = '',
  [switch]$SkipScan
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($Root)) { $Root = $PSScriptRoot }
$sourceRoot = [System.IO.Path]::GetFullPath($Root)
$sourcePrefix = $sourceRoot.TrimEnd([char[]]@(
  [System.IO.Path]::DirectorySeparatorChar,
  [System.IO.Path]::AltDirectorySeparatorChar
)) + [System.IO.Path]::DirectorySeparatorChar

$outputRoot = if ([System.IO.Path]::IsPathRooted($Output)) {
  [System.IO.Path]::GetFullPath($Output)
} else {
  [System.IO.Path]::GetFullPath((Join-Path $sourceRoot $Output))
}

if ($outputRoot.Equals($sourceRoot, [System.StringComparison]::OrdinalIgnoreCase) -or
    -not $outputRoot.StartsWith($sourcePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
  throw 'The deployment directory must be a child of the project directory.'
}

# Refuse overlapping inputs and linked paths BEFORE any writes or scanning.
if ((Split-Path -Parent $outputRoot) -ne $sourceRoot.TrimEnd('\', '/')) {
  throw 'Output must be a direct child of the project directory.'
}
$outputName = Split-Path -Leaf $outputRoot
if ($outputName -match '^\.' -or $outputName -in @('photos','assets','deploy','tests','scripts')) {
  throw "Output overlaps a protected input directory: $outputName"
}
function Assert-NoLinks([string]$Path) {
  $cursor = $Path
  while ($cursor) {
    if (Test-Path -LiteralPath $cursor) {
      if ((Get-Item -LiteralPath $cursor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) {
        throw "Linked paths are not allowed in build input/output: $cursor"
      }
    }
    $parent = Split-Path -Parent $cursor
    if ($parent -eq $cursor) { break }
    $cursor = $parent
  }
}
Assert-NoLinks $outputRoot
$ownerFile = '.gallery-output'
if (Test-Path -LiteralPath $outputRoot) {
  if (-not (Test-Path -LiteralPath (Join-Path $outputRoot $ownerFile))) {
    # Adopt only the known legacy dist format, never an arbitrary existing folder.
    $legacyIndex = Join-Path $outputRoot 'gallery.js'
    $legacy = $outputName -eq 'dist' -and (Test-Path -LiteralPath $legacyIndex)
    if ($legacy) { $legacy = [IO.File]::ReadAllText($legacyIndex).StartsWith('/* Generated by build.ps1.') }
    $unknown = @(Get-ChildItem -LiteralPath $outputRoot -Force | Where-Object {
      $_.Name -notin @('index.html','config.js','gallery.js','assets','media','.nojekyll','favicon.ico','robots.txt','sitemap.xml','CNAME')
    })
    if (-not $legacy -or $unknown.Count) { throw 'Refusing to replace an unowned output directory.' }
  } elseif ([IO.File]::ReadAllText((Join-Path $outputRoot $ownerFile)).Trim() -ne 'gallery-build-v2') {
    throw 'Unrecognized output ownership marker.'
  }
  Get-ChildItem -LiteralPath $outputRoot -Recurse -Force | ForEach-Object { Assert-NoLinks $_.FullName }
}
$cacheRoot = Join-Path $sourceRoot '.gallery-cache'
Assert-NoLinks $cacheRoot
New-Item -ItemType Directory -Path $cacheRoot -Force | Out-Null
$lockPath = Join-Path $cacheRoot 'build.lock'
Assert-NoLinks $lockPath
$buildLock = [IO.File]::Open($lockPath, [IO.FileMode]::OpenOrCreate, [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
$stageRoot = Join-Path $sourceRoot ('.gallery-build-' + [guid]::NewGuid().ToString('N'))
$backupRoot = Join-Path $sourceRoot ('.gallery-backup-' + [guid]::NewGuid().ToString('N'))
function Remove-OwnedTemporary([string]$Path) {
  $absolute = [IO.Path]::GetFullPath($Path)
  if ((Split-Path -Parent $absolute) -ne $sourceRoot.TrimEnd('\', '/') -or
      (Split-Path -Leaf $absolute) -notmatch '^\.gallery-(build|backup)-[a-f0-9]{32}$') {
    throw 'Unsafe temporary directory cleanup.'
  }
  if (Test-Path -LiteralPath $absolute) {
    Assert-NoLinks $absolute
    Get-ChildItem -LiteralPath $absolute -Recurse -Force | ForEach-Object { Assert-NoLinks $_.FullName }
    Remove-Item -LiteralPath $absolute -Recurse -Force
  }
}
try {
New-Item -ItemType Directory -Path $stageRoot | Out-Null
$galleryPath = Join-Path $stageRoot 'gallery.js'
if ($SkipScan) {
  Copy-Item -LiteralPath (Join-Path $sourceRoot 'gallery.js') -Destination $galleryPath
} else {
  & (Join-Path $sourceRoot 'scan.ps1') -Root $sourceRoot -OutputPath $galleryPath -StrictImages
}

Add-Type -AssemblyName System.Drawing
$jpegCodec = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() |
  Where-Object { $_.MimeType -eq 'image/jpeg' } |
  Select-Object -First 1
if ($null -eq $jpegCodec) { throw 'The JPEG encoder is unavailable.' }
$matte = [System.Drawing.ColorTranslator]::FromHtml($MatteColor)

function Apply-ExifOrientation([System.Drawing.Image]$Image) {
  try {
    $property = $Image.GetPropertyItem(0x0112)
    if ($null -eq $property -or $property.Value.Length -lt 2) { return }
    $orientation = [BitConverter]::ToUInt16($property.Value, 0)
    $rotation = switch ($orientation) {
      2 { [System.Drawing.RotateFlipType]::RotateNoneFlipX }
      3 { [System.Drawing.RotateFlipType]::Rotate180FlipNone }
      4 { [System.Drawing.RotateFlipType]::Rotate180FlipX }
      5 { [System.Drawing.RotateFlipType]::Rotate90FlipX }
      6 { [System.Drawing.RotateFlipType]::Rotate90FlipNone }
      7 { [System.Drawing.RotateFlipType]::Rotate270FlipX }
      8 { [System.Drawing.RotateFlipType]::Rotate270FlipNone }
      default { [System.Drawing.RotateFlipType]::RotateNoneFlipNone }
    }
    if ($rotation -ne [System.Drawing.RotateFlipType]::RotateNoneFlipNone) {
      $Image.RotateFlip($rotation)
    }
  } catch {
    # Images without an orientation tag need no correction.
  }
}

function Save-ResizedJpeg(
  [System.Drawing.Image]$sourceImage,
  [string]$Destination,
  [int]$MaxSide,
  [int]$Quality
) {
  & {
    $largestSide = [Math]::Max($sourceImage.Width, $sourceImage.Height)
    $scale = [Math]::Min(1.0, [double]$MaxSide / [double]$largestSide)
    $width = [Math]::Max(1, [int][Math]::Round($sourceImage.Width * $scale))
    $height = [Math]::Max(1, [int][Math]::Round($sourceImage.Height * $scale))

    $bitmap = [System.Drawing.Bitmap]::new(
      $width,
      $height,
      [System.Drawing.Imaging.PixelFormat]::Format24bppRgb
    )
    try {
      $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
      try {
        $graphics.Clear($matte)
        $graphics.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceOver
        $graphics.CompositingQuality = [System.Drawing.Drawing2D.CompositingQuality]::HighQuality
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
        $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
        $destinationRect = [System.Drawing.Rectangle]::new(0, 0, $width, $height)
        $graphics.DrawImage(
          $sourceImage,
          $destinationRect,
          0,
          0,
          $sourceImage.Width,
          $sourceImage.Height,
          [System.Drawing.GraphicsUnit]::Pixel
        )
      } finally {
        $graphics.Dispose()
      }

      $encoderParameters = [System.Drawing.Imaging.EncoderParameters]::new(1)
      try {
        $encoderParameters.Param[0] = [System.Drawing.Imaging.EncoderParameter]::new(
          [System.Drawing.Imaging.Encoder]::Quality,
          [long]$Quality
        )
        $bitmap.Save($Destination, $jpegCodec, $encoderParameters)
      } finally {
        $encoderParameters.Dispose()
      }
    } finally {
      $bitmap.Dispose()
    }
  }
}

function Get-SourcePath([string]$RelativePath) {
  $localPath = $RelativePath.Replace('/', [System.IO.Path]::DirectorySeparatorChar)
  $fullPath = [System.IO.Path]::GetFullPath((Join-Path $sourceRoot $localPath))
  if (-not $fullPath.StartsWith($sourcePrefix, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "Photo path escapes the project directory: $RelativePath"
  }
  if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
    throw "Missing photo: $RelativePath"
  }
  Assert-NoLinks $fullPath
  return $fullPath
}

$gallerySource = [System.IO.File]::ReadAllText($galleryPath, [System.Text.Encoding]::UTF8)
$marker = 'window.GALLERY_DATA ='
$markerIndex = $gallerySource.IndexOf($marker, [System.StringComparison]::Ordinal)
if ($markerIndex -lt 0) { throw 'gallery.js does not contain window.GALLERY_DATA.' }
$jsonText = $gallerySource.Substring($markerIndex + $marker.Length).Trim()
if ($jsonText.EndsWith(';')) { $jsonText = $jsonText.Substring(0, $jsonText.Length - 1) }
$gallery = $jsonText | ConvertFrom-Json

$thumbDirectory = Join-Path $stageRoot 'media\thumb'
$detailDirectory = Join-Path $stageRoot 'media\detail'
New-Item -ItemType Directory -Path $thumbDirectory -Force | Out-Null
New-Item -ItemType Directory -Path $detailDirectory -Force | Out-Null

Copy-Item -LiteralPath (Join-Path $sourceRoot 'config.js') -Destination $stageRoot
Copy-Item -LiteralPath (Join-Path $sourceRoot 'assets') -Destination $stageRoot -Recurse

$buildId = (Get-Date).ToUniversalTime().ToString('yyyyMMddHHmmss')
$indexSource = [System.IO.File]::ReadAllText(
  (Join-Path $sourceRoot 'index.html'),
  [System.Text.Encoding]::UTF8
)
$indexOutput = [regex]::Replace($indexSource, '(src|href)="([^"?]+)\?v=[^"\s>]+"', {
  param($match)
  $resource = $match.Groups[2].Value
  $version = if ($resource -eq 'gallery.js') { $buildId } else {
    (Get-FileHash -LiteralPath (Join-Path $sourceRoot $resource) -Algorithm SHA256).Hash.Substring(0,16).ToLowerInvariant()
  }
  return $match.Groups[1].Value + '="' + $resource + '?v=' + $version + '"'
})
$utf8 = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText((Join-Path $stageRoot 'index.html'), $indexOutput, $utf8)

foreach ($optionalName in @('favicon.ico', 'robots.txt', 'sitemap.xml', 'CNAME')) {
  $optionalPath = Join-Path $sourceRoot $optionalName
  if (Test-Path -LiteralPath $optionalPath -PathType Leaf) {
    Copy-Item -LiteralPath $optionalPath -Destination $stageRoot
  }
}

$processed = 0
$encoded = 0
$reused = 0
$mediaCache = Join-Path $cacheRoot 'images-v2'
Assert-NoLinks $mediaCache
New-Item -ItemType Directory -Path $mediaCache -Force | Out-Null
$encoderIdentity = [System.Drawing.Image].Assembly.GetName().Version.ToString()
foreach ($item in @($gallery.items)) {
  $sourcePath = Get-SourcePath ([string]$item.file)
  $sourceHash = (Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()
  $variants = @()
  foreach ($side in @(@(320,640,$ThumbnailMaxSide) | Where-Object { $_ -le $ThumbnailMaxSide } | Sort-Object -Unique)) {
    $variants += [pscustomobject]@{ side=[int]$side; quality=$ThumbnailQuality; kind='thumb' }
  }
  foreach ($side in @(@(1600,$DetailMaxSide) | Where-Object { $_ -le $DetailMaxSide } | Sort-Object -Unique)) {
    $variants += [pscustomobject]@{ side=[int]$side; quality=$DetailQuality; kind='detail' }
  }
  $sourceImage = $null
  $thumbs = @(); $details = @()
  try {
    foreach ($variant in $variants) {
      $identity = "$sourceHash|$($variant.side)|$($variant.quality)|$MatteColor|oriented-icc-matte-jpeg-v2|$encoderIdentity"
      $sha = [Security.Cryptography.SHA256]::Create()
      try { $key = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($identity)))).Replace('-','').ToLowerInvariant() }
      finally { $sha.Dispose() }
      $name = $key + '.jpg'
      $cached = Join-Path $mediaCache $name
      Assert-NoLinks $cached
      if (-not (Test-Path -LiteralPath $cached)) {
        if ($null -eq $sourceImage) {
          $sourceImage = [System.Drawing.Image]::FromFile($sourcePath, $true)
          Apply-ExifOrientation $sourceImage
        }
        $pending = $cached + '.pending.jpg'
        Assert-NoLinks $pending
        Save-ResizedJpeg $sourceImage $pending $variant.side $variant.quality
        Move-Item -LiteralPath $pending -Destination $cached -Force
        $encoded++
      } else { $reused++ }
      $relative = 'media/' + $variant.kind + '/' + $name
      Copy-Item -LiteralPath $cached -Destination (Join-Path $stageRoot $relative)
      $entry = [pscustomobject]@{ side=$variant.side; file=$relative }
      if ($variant.kind -eq 'thumb') { $thumbs += $entry } else { $details += $entry }
    }
  } finally { if ($null -ne $sourceImage) { $sourceImage.Dispose() } }
  $item.file = $details[-1].file
  $item | Add-Member -NotePropertyName thumb -NotePropertyValue $thumbs[-1].file -Force
  $item | Add-Member -NotePropertyName thumbnails -NotePropertyValue @($thumbs) -Force
  $item | Add-Member -NotePropertyName details -NotePropertyValue @($details) -Force
  if (-not $item.PSObject.Properties['id']) { $item | Add-Member -NotePropertyName id -NotePropertyValue $sourceHash.Substring(0,24) }
  $processed++
  Write-Host ('[{0}/{1}] {2}' -f $processed, @($gallery.items).Count, $item.title)
}

$gallery | Add-Member -NotePropertyName build -NotePropertyValue ([ordered]@{
  id = $buildId; thumbnailMaxSide = $ThumbnailMaxSide; detailMaxSide = $DetailMaxSide; format = 'jpeg'
}) -Force
$galleryJson = ConvertTo-Json -InputObject $gallery -Depth 10
$galleryOutput = "/* Generated by build.ps1. Do not edit manually. */`r`nwindow.GALLERY_DATA = " + $galleryJson + ";`r`n"
[IO.File]::WriteAllText((Join-Path $stageRoot 'gallery.js'), $galleryOutput, $utf8)
[IO.File]::WriteAllText((Join-Path $stageRoot '.nojekyll'), '', $utf8)
[IO.File]::WriteAllText((Join-Path $stageRoot $ownerFile), 'gallery-build-v2', $utf8)

# Standalone photo pages provide static text and share metadata without a server.
$pageRoot = Join-Path $stageRoot 'photo'
New-Item -ItemType Directory -Path $pageRoot -Force | Out-Null
foreach ($item in @($gallery.items)) {
  $id = [string]$item.id
  if ($id -notmatch '^[a-zA-Z0-9_-]+$') { throw "Invalid public photo ID: $id" }
  $title = [Net.WebUtility]::HtmlEncode([string]$item.title)
  $description = if ($item.PSObject.Properties['description']) { [Net.WebUtility]::HtmlEncode([string]$item.description) } else { '' }
  $imagePath = '../' + [Net.WebUtility]::HtmlEncode([string]$item.file)
  $meta = ''
  if ($SiteUrl) {
    $baseUri = [uri]($SiteUrl.TrimEnd('/') + '/')
    if (-not $baseUri.IsAbsoluteUri -or $baseUri.Scheme -notin @('https','http')) { throw 'SiteUrl must be an absolute HTTP(S) URL.' }
    $absoluteImage = [Net.WebUtility]::HtmlEncode(([uri]::new($baseUri, [string]$item.file)).AbsoluteUri)
    $canonical = [Net.WebUtility]::HtmlEncode(([uri]::new($baseUri, ('photo/' + $id + '.html'))).AbsoluteUri)
    $meta = '<link rel="canonical" href="' + $canonical + '"><meta property="og:url" content="' + $canonical + '"><meta property="og:image" content="' + $absoluteImage + '">'
  }
  $html = '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>' + $title + '</title><meta property="og:type" content="article"><meta property="og:title" content="' + $title + '"><meta name="description" content="' + $description + '"><meta property="og:description" content="' + $description + '">' + $meta + '<link rel="stylesheet" href="../assets/photo.css"><main><h1>' + $title + '</h1><a href="../index.html#photo=' + $id + '"><img src="' + $imagePath + '" alt="' + $title + '"></a><p>' + $description + '</p><a href="../index.html#photo=' + $id + '">Explore the gallery</a></main></html>'
  [IO.File]::WriteAllText((Join-Path $pageRoot ($id + '.html')), $html, $utf8)
}

# Roll back if promotion fails. The previous deployment survives build failures.
if (Test-Path -LiteralPath $outputRoot) { Move-Item -LiteralPath $outputRoot -Destination $backupRoot }
try { Move-Item -LiteralPath $stageRoot -Destination $outputRoot }
catch {
  if (Test-Path -LiteralPath $backupRoot) { Move-Item -LiteralPath $backupRoot -Destination $outputRoot }
  throw
}
Remove-OwnedTemporary $backupRoot
Write-Host ('Build complete: {0}; encoded {1}, reused {2}' -f $outputRoot, $encoded, $reused) -ForegroundColor Green
} finally {
  Remove-OwnedTemporary $stageRoot
  $buildLock.Dispose()
}
